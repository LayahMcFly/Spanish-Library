from playwright.sync_api import sync_playwright
with sync_playwright() as p:
    b = p.chromium.launch(executable_path='/usr/bin/google-chrome', args=['--no-sandbox'])
    ctx = b.new_context(viewport={'width':412,'height':880})
    pg = ctx.new_page()
    errs=[]; pg.on('console', lambda m: errs.append(m.text) if m.type=='error' else None)
    pg.goto('http://localhost:8765/index.html'); pg.wait_for_timeout(3000)
    print('sw controlled after reload:', end=' ')
    pg.reload(); pg.wait_for_timeout(2500)
    print(pg.evaluate("!!navigator.serviceWorker.controller"))
    ctx.set_offline(True)
    pg.reload(); pg.wait_for_timeout(2500)
    print('title offline:', pg.title(), '| cards:', pg.locator('.book, .bookcard, [data-act="openBook"]').count())
    pg.goto('http://localhost:8765/index.html#/read/rosas/1/0'); pg.wait_for_timeout(1500)
    print('sentences offline:', pg.locator('.sent').count())
    fonts = pg.evaluate("Array.from(document.fonts).filter(f=>f.status=='loaded').map(f=>f.family)")
    print('fonts loaded:', sorted(set(fonts)))
    print('errors:', errs[:5])
    b.close()
