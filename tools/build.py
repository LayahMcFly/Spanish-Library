#!/usr/bin/env python3
"""Regenerates www/sw.js (precache list + cache name) and www/version.json from APP_VERSION in www/js/core.js.
Run after any change to files in www/:  python3 tools/build.py"""
import os, re, json
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'www')
core = open(os.path.join(root, 'js', 'core.js'), encoding='utf8').read()
ver = re.search(r"APP_VERSION = '([^']+)'", core).group(1)
files = []
for d, _, fs in os.walk(root):
    for f in fs:
        p = os.path.relpath(os.path.join(d, f), root).replace(os.sep, '/')
        if p in ('sw.js', 'version.json'): continue
        files.append(p)
files.sort()
assets = ['./'] + files
sw = f"""/* Service worker: caches the whole app so it works with no internet. Generated by tools/build.py */
const VERSION = '{ver}';
const CACHE = 'biblioteca-rosas-' + VERSION;
const ASSETS = {json.dumps(assets, indent=1)};
self.addEventListener('install', e => {{
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(ASSETS)).then(() => self.skipWaiting()));
}});
self.addEventListener('activate', e => {{
  e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k.startsWith('biblioteca-rosas-') && k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim()));
}});
self.addEventListener('fetch', e => {{
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== location.origin) return;
  if (url.pathname.endsWith('/version.json')) {{
    e.respondWith(fetch(req).catch(() => new Response('{{}}', {{ headers: {{ 'Content-Type': 'application/json' }} }})));
    return;
  }}
  e.respondWith(caches.match(req, {{ ignoreSearch: true }}).then(hit => hit || fetch(req).then(res => {{
    if (res.ok) {{ const copy = res.clone(); caches.open(CACHE).then(c => c.put(req, copy)); }}
    return res;
  }}).catch(() => req.mode === 'navigate' ? caches.match('./index.html') : Promise.reject('offline'))));
}});
"""
open(os.path.join(root, 'sw.js'), 'w', encoding='utf8').write(sw)
open(os.path.join(root, 'version.json'), 'w').write(json.dumps({'version': ver}) + '\n')
print('built sw.js for version', ver, 'with', len(assets), 'assets')
